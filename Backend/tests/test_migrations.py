"""The migration history and ``Base.metadata`` agree.

``alembic check`` also runs from the command line; these tests keep the property in the
suite so a model change that forgets a revision fails a test, not a later review.
"""

import pytest
import sqlalchemy as sa
from alembic import command
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import Connection, Engine


def test_alembic_check_finds_no_drift(database_engine: Engine, alembic_config: Config) -> None:
    # database_engine applies the bootstrap and `upgrade head` before the comparison.
    command.check(alembic_config)


def test_alembic_check_detects_a_changed_server_default(
    db: Connection, alembic_config: Config
) -> None:
    db.execute(sa.text("alter table staff alter column active set default false"))
    alembic_config.attributes["connection"] = db
    try:
        with pytest.raises(AutogenerateDiffsDetected, match="active"):
            command.check(alembic_config)
    finally:
        alembic_config.attributes.pop("connection", None)
